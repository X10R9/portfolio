/**
 * Static deployments (Cloudflare Pages, Netlify, GitHub Pages) have no Node API.
 * The site then falls back to src/data/site-defaults.json, so copy the latest
 * locally-saved content there before building.
 *
 * It also regenerates functions/_lib/defaults.js, used by the Cloudflare Pages
 * Functions API to seed KV when it has no saved site yet.
 *
 * Run automatically by "npm run build" (prebuild).
 */
import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const liveFile = path.join(root, 'server', 'data', 'site.json')
const defaultsFile = path.join(root, 'src', 'data', 'site-defaults.json')
const functionDefaultsFile = path.join(root, 'functions', '_lib', 'defaults.js')

const live = fs.existsSync(liveFile)
  ? JSON.parse(fs.readFileSync(liveFile, 'utf8'))
  : null
const current = fs.existsSync(defaultsFile)
  ? JSON.parse(fs.readFileSync(defaultsFile, 'utf8'))
  : null
const source = live || current

if (!source) {
  console.log('[data] no site data found, skipping sync')
  process.exit(0)
}

if (live && (!current || JSON.stringify(live) !== JSON.stringify(current))) {
  fs.writeFileSync(defaultsFile, JSON.stringify(live, null, 2) + '\n', 'utf8')
  console.log('[data] synced server/data/site.json -> src/data/site-defaults.json')
} else {
  console.log('[data] static defaults already match server/data/site.json')
}

fs.mkdirSync(path.dirname(functionDefaultsFile), { recursive: true })
fs.writeFileSync(
  functionDefaultsFile,
  `// Generated by scripts/sync-data.mjs. Do not edit manually.\nexport default ${JSON.stringify(source, null, 2)}\n`,
  'utf8'
)
console.log('[data] regenerated functions/_lib/defaults.js')
